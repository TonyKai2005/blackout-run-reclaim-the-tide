import type { GameState } from './state';

/** Short, contextual hints for the island crew. Dialogue has no mission side effects. */
export function crewDialogue(id: string, state: GameState, visit: number): string {
  const phase = state.phase;
  let hint = '';
  let context = '';
  switch (id) {
    case 'crew_dock':
      hint = phase === 1
        ? state.items.battery.status === 'installed' ? 'The dock grid has the battery. Head inland to clear and start the recovery line.' : 'The reusable battery is on the north pier. Bring it to the Dock Grid Slot.'
        : phase === 2 ? 'The treatment hall is east of the basin. Follow the marker to the next intake or filter part.'
          : 'When the services have held steady, the rescue launch at this dock is your exit.';
      context = 'I keep the rescue launch ready. Your marker points to the next essential job.';
      break;
    case 'crew_coast':
      hint = phase === 1 ? 'The storm left two waste bundles on the coast. Feed both into the sorter after clearing its jam.'
        : phase === 2 ? 'The intake screens caught storm debris. Clear both before starting the water process.'
          : 'The shoreline looks brighter, but the recovery line must stay powered for final capture.';
      context = 'Recovered material is counted once, when the powered line actually processes it.';
      break;
    case 'crew_water':
      hint = phase === 1 ? 'We need stable power before the water crew can restart the pumps.'
        : phase === 2 ? 'Clear the intakes, fit the reused frame and new cartridge, then use the Water Treatment Switch.'
          : 'Keep the water treatment branch supplied while wind generation and recovery stabilize.';
      context = 'The status light means the treatment equipment is running. It does not certify drinking water.';
      break;
    case 'crew_battery':
      hint = state.items.battery.status === 'installed'
        ? 'The reused battery is connected. If stored energy runs low, the Dock Grid Slot can import a tracked emergency pack.'
        : 'The reusable battery is on this pier. Carry it to the Dock Grid Slot.';
      context = 'Imported battery energy and energy generated by wind are recorded separately.';
      break;
    case 'crew_recovery':
      hint = !state.goals.sorterJamCleared ? 'The conveyor is jammed. Clear the blockage before loading recovered waste.'
        : phase === 1 ? 'Deliver both waste bundles and start the recovery line at its switch.'
          : phase === 2 ? 'Keep the recovery line supplied while the water crew works.'
            : 'The final capture console needs both wind generation and the recovery line.';
      context = 'The sorter separates recovered material only while its three-kilowatt load is powered.';
      break;
    case 'crew_filter':
      hint = phase === 1 ? 'The reused filter frame is ready nearby. Water work starts after recovery stabilizes.'
        : phase === 2 ? !state.goals.intakeACleared || !state.goals.intakeBCleared
          ? 'Clear both intake blockages first. Then bring the frame and cartridge to the filter rack.'
          : state.items.filter_frame.status !== 'installed' || state.items.filter_cartridge.status !== 'installed'
            ? 'Fit the reused frame and the new cartridge at the filter rack.'
            : 'The filter is installed. Use the Water Treatment Switch and keep the pumps powered.'
          : 'The reused filter frame is still helping the treatment equipment run.';
      context = 'Reusing a sound frame saves a component; the filter cartridge still needs replacing.';
      break;
    case 'crew_wind':
      hint = phase < 3 ? 'The turbines stay in protective shutdown while the wind is too strong.'
        : state.items.wind_converter.status !== 'installed' ? 'Find the wind control module and fit it at the control socket.'
          : !state.goals.bossLeftDisabled || !state.goals.bossRightDisabled ? 'Hit both exposed nodes on the large debris machine with seed pods.'
            : 'Watch the wind console. Restart generation only when the safety window opens.';
      context = 'A turbine can generate again after the gusts fall below the game’s safe threshold.';
      break;
    default:
      hint = 'Follow the current objective marker to the next repair.';
      context = 'Every recovered part gives the island another chance.';
  }
  return visit % 2 === 0 ? hint : context;
}
